namespace SAloha.Api.Modules.IncidentManagement;

// Réponses de l'API (A2, ADR-0016) : DTO explicites, noms de champs inchangés pour le frontend.
// Un champ ajouté à une entité n'est exposé qu'en l'ajoutant ici.

public record IncidentView(
    string? Impact,
    string? Urgency,
    string? Priority,
    string? Category,
    string? AffectedService,
    int? ServiceId,
    bool IsMajor,
    bool IsSecurity,
    string? Channel,
    string? CallerId,
    string? CallerDisplayName,
    string? EscalationReason,
    DateTime? QualifiedAt,
    string? QualifiedBy,
    bool? Nis2Important,
    string? Nis2Reason,
    bool? PersonalDataBreach,
    string? PersonalDataBreachReason,
    string? Resolution,
    string? ResolutionCode,
    DateTime? FirstResponseAt,
    DateTime? ResolvedAt,
    DateTime? ClosedAt,
    int ReopenCount,
    DateTime? OccurredAt,
    DateTime? ResolutionDueAt,
    DateTime? ResponseDueAt,
    bool OwnerChanged,
    bool? FirstContactResolution,
    string? ReopenReason,
    string? OnHoldReason,
    DateTime? OnHoldSince,
    int HeldMinutes,
    int? ParentId,
    string? HoldFollowUp,
    string? SlaState,
    int Id,
    int PerimeterId,
    string? Reference,
    string? Title,
    string? Description,
    string? Status,
    string? OwnerType,
    string? OwnerId,
    string? OwnerDisplayName,
    string? CreatedBy,
    string? CreatedByDisplayName,
    DateTime CreatedAt,
    DateTime UpdatedAt,
    IReadOnlyList<UnresolvedChildView>? UnresolvedChildren = null)
{
    public static IncidentView From(Incident e) => new(
        e.Impact,
        e.Urgency,
        e.Priority,
        e.Category,
        e.AffectedService,
        e.ServiceId,
        e.IsMajor,
        e.IsSecurity,
        e.Channel,
        e.CallerId,
        e.CallerDisplayName,
        e.EscalationReason,
        e.QualifiedAt,
        e.QualifiedBy,
        e.Nis2Important,
        e.Nis2Reason,
        e.PersonalDataBreach,
        e.PersonalDataBreachReason,
        e.Resolution,
        e.ResolutionCode,
        e.FirstResponseAt,
        e.ResolvedAt,
        e.ClosedAt,
        e.ReopenCount,
        e.OccurredAt,
        e.ResolutionDueAt,
        e.ResponseDueAt,
        e.OwnerChanged,
        e.FirstContactResolution,
        e.ReopenReason,
        e.OnHoldReason,
        e.OnHoldSince,
        e.HeldMinutes,
        e.ParentId,
        e.HoldFollowUp(DateTime.UtcNow),
        e.SlaState,
        e.Id,
        e.PerimeterId,
        e.Reference,
        e.Title,
        e.Description,
        e.Status,
        e.OwnerType,
        e.OwnerId,
        e.OwnerDisplayName,
        e.CreatedBy,
        e.CreatedByDisplayName,
        e.CreatedAt,
        e.UpdatedAt);
}

/// <summary>INC-16 : enfant laissé ouvert par la résolution de son parent, et pourquoi (réponse de cette résolution seulement).</summary>
public record UnresolvedChildView(string Reference, string Reason);
